/** Available text keys. */
export type TextKey = keyof (typeof TEXTS)["es"];

/** Event fired on document when the language changes (to repaint dynamic texts). */
export const LANGUAGE_CHANGED = "quizmania:language-changed";

/** Active language. */
let currentLanguage: Language = "es";

/** Browser's preferred language (Spanish if it starts with "es", English otherwise). */
export function detectBrowserLanguage(): Language {
    return navigator.language.toLowerCase().startsWith("es") ? "es" : "en";
}

/** Active language. */
export function getLanguage(): Language {
    return currentLanguage;
}

/**
 * Changes the active language and translates the whole page again.
 * @param language Language to activate.
 */
export function setLanguage(language: Language): void {
    currentLanguage = language;
    translateDocument();
    document.dispatchEvent(new CustomEvent(LANGUAGE_CHANGED));
}

/**
 * Text of a key in the active language.
 * @param key Dictionary key.
 */
export function t(key: TextKey): string {
    return TEXTS[currentLanguage][key];
}

/**
 * Whether a string is a text key (used to validate data-text attributes in tests).
 * @param key Possible key.
 */
export function isTextKey(key: string): key is TextKey {
    return key in TEXTS.es;
}

/** Applies the active language to every data-text* element, the lang attribute and the meta description. */
export function translateDocument(): void {
    document.documentElement.lang = currentLanguage;
    document.querySelector('meta[name="description"]')?.setAttribute("content", t("description"));
    document.querySelectorAll<HTMLElement>("[data-text]").forEach((element) => {
        element.textContent = t(element.dataset.text as TextKey);
    });
    document.querySelectorAll<HTMLElement>("[data-text-aria]").forEach((element) => {
        element.setAttribute("aria-label", t(element.dataset.textAria as TextKey));
    });
    document.querySelectorAll<HTMLInputElement>("[data-text-placeholder]").forEach((element) => {
        element.placeholder = t(element.dataset.textPlaceholder as TextKey);
    });
}
